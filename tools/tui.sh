# Show a menu that stays open: loop LABEL HEADER LINES ACT [ART].
#
# LINES prints the lines, 'ACT KEY' does the change and may set '$note'.
# ART goes above HEADER, under an empty line. Esc leaves.
loop() {
    local lines pick header pos=1 banner="${5:-}"
    if [ "${config_menu:-0}" = 1 ]; then
        local title
        title=$(config_banner "$1")
        banner="$title${banner:+
$banner}"
    fi
    note=''
    while :; do
        lines=$("$3")
        # A last line of one space makes an empty line above the list.
        header=$([ -z "$banner" ] || printf ' \n%s\n \n' "$banner"; center "$2"; [ -z "$note" ] || center "$note"; echo ' ')
        pick=$(printf '%s\n' "$lines" |
            menu --border-label=" $(cap "$1") " --header="$header" --bind="load:pos($pos)") || return 0
        pos=$(printf '%s\n' "$lines" | grep -nxF -- "$pick" | cut -d: -f1)
        pick=${pick%%"$tab"*}
        [ "$pick" != - ] || continue
        "$4" "$pick"
    done
}

