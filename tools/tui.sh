# Shhware tui API 1

# Show a menu. The lines are "key<TAB>text": only the text shows, the key
# tells what was picked.
menu() {
    fzf --info=hidden --no-input --delimiter="$tab" --with-nth=2 "$@"
}

# Print TEXT with a capital first letter. Menus show it so, the keys stay.
cap() {
    printf '%s%s' "$(printf '%.1s' "$1" | tr '[:lower:]' '[:upper:]')" "${1#?}"
}

# Print a menu line: line KEY BOX LABEL TEXT.
line() {
    printf '%s\t%-3s %-*s %s\n' "$1" "$2" "${label_width:-14}" "$(cap "$3")" "$4"
}

# Print a line with [x] or [ ]: yes_no NAME TEXT [DEFAULT].
yes_no() {
    if [ "$(setting "$1" "${3:-yes}")" = yes ]; then line "$1" '[x]' "${4:-$1}" "$2"; else line "$1" '[ ]' "${4:-$1}" "$2"; fi
}

# Print the shown text of KEY in LIST: label_of LIST KEY.
label_of() {
    printf '%s\n' "$1" | awk -F "$tab" -v k="$2" '$1 == k { print $2 }'
}

# Pick one of LIST and print its key (nothing on Esc): choose LABEL LIST.
choose() {
    local banner
    banner=$(config_banner "$1")
    printf '%s\n' "$2" | menu --border-label=" $(cap "$1") " --header="$(printf ' \n%s\n ' "$banner")" | cut -f1
}

# Read the width before menu output is piped into fzf.
menu_columns() {
    [ -t 2 ] || return 0
    stty size <&2 2>/dev/null | cut -d' ' -f2
}

# Print TEXT in the middle of the menu: center TEXT [WIDTH].
#
# The middle is the window width minus the border and the cursor column.
# With no terminal the text stays as it is. WIDTH is for non-ASCII text:
# dash counts bytes in '${#1}'.
center() {
    local cols pad
    cols=$(menu_columns)
    pad=$(( (${cols:-0} - 4 - ${2:-${#1}}) / 2 ))
    [ "$pad" -gt 0 ] || pad=0
    printf '%*s%s\n' "$pad" '' "$1"
}

# Keep the artwork centered as a block, including its leading spaces.
banner_block() {
    local cols=${1:-0} width=$2 pad
    [ "$cols" -eq 0 ] || [ "$cols" -ge "$((width + 4))" ] || return 0
    pad=$(( (cols - width - 4) / 2 ))
    [ "$pad" -gt 0 ] || pad=0
    sed "s/^/$(printf '%*s' "$pad" '')/"
}

